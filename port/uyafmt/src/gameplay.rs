/// What a table's decoder needs besides its bytes.
struct Ctx<'a> {
    /// The table's offset in the block.
    at: usize,
    /// The sizes of the +0x5C table's entries (empty when the block has none).
    entries: Vec<usize>,
    /// The whole block and its tables: (header offset, table offset, extent).
    g: &'a [u8],
    tabs: Vec<(usize, usize, usize)>,
}

impl Ctx<'_> {
    /// The bytes of the table the header word at `off` names.
    fn table(&self, off: usize) -> Result<&[u8], String> {
        let &(_, at, end) = self.tabs.iter().find(|x| x.0 == off).ok_or_else(|| format!("the block has no +{off:#04x} table"))?;
        Ok(&self.g[at..end])
    }
}

type Fdec = fn(&mut Fields, &Ctx) -> Result<(), String>;
type Tdec = fn(&mut Tracker, &mut Node, &[u8], &Ctx) -> Result<(), String>;
type Odec = fn(&mut Fields, &Ctx, &mut Out) -> Result<(), String>;

enum Run {
    /// A decoder that only marks fields of its table.
    F(Fdec),
    /// A decoder that also places finer structure lines inside its table.
    T(Tdec),
    /// A decoder that marks its fields and returns its data into the block's `Out`.
    O(Odec),
}

