//! The LEVEL gameplay block's header and tables (unpacked), as the level loader func_L01_004252F0 (the same function in all 34
//! story levels; PAL func_L01_00428098) and the code that reads what it keeps read them.
//!
//! The block starts with 40 words: byte offsets of the tables, in no particular order (+0x00 to +0x98; +0x9C is zero and read by
//! nothing; +0x90 is zero in levels 24, 30, 34 and 35, where the loader skips that table). Each table runs to the next table's start
//! (or the block's end); a table whose layout is settled ends before it by less than 16 zero bytes of alignment padding (less than
//! 64 for +0x90 and +0x98, which the next table's 64-byte alignment pads). The loader unpacks the block, copies what it needs out and
//! never reads the block again (no reader of its tables was found among the other code that names the buffer's address), so a table
//! the loader does not read is read by nothing at all (+0x30, +0x3C, +0x48 here).
//!
//! What the loader does with each table:
//! - +0x00: nine words (clear colour, three bytes, floats), a flag and the floats it gates, four floats, three words, a count at
//!   +0x68 and that many 0x20-byte records starting at +0x5C (the first record's +0x0C is the count itself; one record's space is
//!   always present), then two words.
//! - +0x04: count and up to 12 0x40-byte records, copied to 0x1F17C0 (the level's light sets). +0x08: count and 0x20-byte camera
//!   records (u32, three floats, three floats, entry index). +0x0C: count and 0x90-byte records (s16 type, two runtime words, entry
//!   index, ...). +0x68, +0x6C and +0x70: count and 0x80-byte volume records (cuboids, spheres, cylinders: a point is tested in
//!   the volume's local space), +0x74 the same kind (always empty), +0x84 (n 16-byte records, then n 0x80-byte ones), +0x8C (0x20-byte
//!   zone records): a 0x10-byte header (count, then three words nothing reads) and the records.
//! - +0x10 to +0x2C: eight text tables, one per language (the byte at 0x143A07 picks one: func_L01_004252F0 reads the table's
//!   count and size, copies the entries and strings out and adds the copy's address to every entry's offset).
//! - +0x34 and +0x40: count and 0x60-byte tie or 0x70-byte shrub instance records (the loader builds the instance array and the
//!   matrix array from them).
//! - +0x38, +0x44 and +0x50: count and byte size, one offset per list (-1 for none), then the lists: u16 values whose top bit marks
//!   a list's last value; +0x50's values are remapped through the level's id table by the loader.
//! - +0x4C: the moby instance records (0x88 bytes each); +0x54: size, count, the data, then count 8-byte fix-ups. +0x5C: (offset,
//!   size) entries that tile the blob at +0x60 (each is the data of one +0x08 record, +0x0C record or moby); +0x58 and +0x64:
//!   (entry index, byte offset) pairs ended by a negative index, naming words in the blob to remap or to relocate.
//! - +0x78: paths; +0x7C: rails; +0x80: a 0x800-byte slot array and n 16-byte records; +0x88: a zero buffer; +0x90: three arrays of
//!   (key, id) pairs (terrain chunks, tie instances, ids); +0x98: volume cells.
//! - +0x94: a stream of (s16 instance index, s16 count, count u16 colours) ended by an index of -1.

