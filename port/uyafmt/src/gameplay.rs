/// The unpacked gameplay block: the header, then every table.
pub fn gameplay(t: &mut Tracker, root: &mut Node, g: &[u8]) -> Result<Gameplay, String> {
    let hl = t.line(
        G,
        "header (40 table offsets)",
        "gameplay::header",
        "func_L01_004252F0 (same in all 34 story levels) reads the offsets +0x00 to +0x98 (+0x10 to +0x2C by language); +0x9C is zero (read by nothing)",
        Space::Unpacked,
    );
    let mut h = t.child(root, hl, 0, 0xa0.min(g.len() as u64));
    let tables = header(&mut h, g);
    t.close(h);
    // A header that cannot be read leaves the rest of the block as unknown bytes (the header line carries the error).
    let tables = tables?;
    let mut out = Out::default();
    let mut failed = Vec::new();
    let mut starts: Vec<usize> = tables.iter().map(|x| x.1).collect();
    starts.sort_unstable();
    starts.push(g.len());
    let extent = |at: usize| starts.iter().copied().find(|&s| s > at);
    let entries = match tables.iter().find(|x| x.0 == 0x5c) {
        Some(&(_, at)) => entry_sizes(&g[at..extent(at).unwrap_or(g.len())]),
        None => Vec::new(),
    };
    let mut tabs = Vec::new();
    for &(off, at) in &tables {
        tabs.push((off, at, extent(at).ok_or_else(|| format!("gameplay table +{off:#04x} at {at:#x}: no end"))?));
    }
    for &(off, at, end) in &tabs {
        let k = kind(off);
        let name = if k.name.is_empty() { format!("table at header +{off:#04x}") } else { k.name.to_string() };
        let l = t.line(G, &name, k.decoder, k.game, Space::Unpacked);
        if !k.note.is_empty() {
            t.note(l, k.note);
        }
        let mut n = t.child(root, l, at as u64, (end - at) as u64);
        let ctx = Ctx { at, entries: entries.clone(), g, tabs: tabs.clone() };
        let r = match k.run {
            Some(Run::F(run)) => {
                let mut f = Fields::new(&g[at..end], &mut n);
                run(&mut f, &ctx)
            }
            Some(Run::T(run)) => run(t, &mut n, &g[at..end], &ctx),
            Some(Run::O(run)) => {
                let mut f = Fields::new(&g[at..end], &mut n);
                let r = run(&mut f, &ctx, &mut out);
                if let Err(e) = &r {
                    failed.push(format!("{name}: {e}"));
                }
                r
            }
            None => Ok(()),
        };
        if let Err(e) = r {
            n.fail(e);
        }
        t.close(n);
    }
    // A table whose data the port takes stops the block; the others' errors stay on their lines.
    if !failed.is_empty() {
        return Err(failed.join("; "));
    }
    Ok(Gameplay {
        light_sets: out.light_sets,
        fog: out.fog.ok_or("the block has no settings table")?,
        chunk_zones: out.chunk_zones,
        level_chunks: out.level_chunks.ok_or("the block has no settings table")?,
        ties: out.ties.ok_or("the block has no tie instance table")?,
        shrubs: out.shrubs.ok_or("the block has no shrub instance table")?,
        tie_zones: out.tie_zones,
    })
}

/// The 40 offsets: (header offset, table offset) of every table the block holds.
fn header(h: &mut Node, g: &[u8]) -> Result<Vec<(usize, usize)>, String> {
    if g.len() < 0xa0 {
        let e = format!("gameplay block of {:#x} bytes is shorter than its 0xA0-byte header", g.len());
        h.fail(e.clone());
        return Err(e);
    }
    let mut f = Fields::new(&g[..0xa0], h);
    let r = (|| {
        let mut out: Vec<(usize, usize)> = Vec::new();
        for i in 0..39usize {
            let p = f.u32(4 * i)? as usize;
            if p == 0 {
                // Only +0x90 may be absent.
                if i != 0x90 / 4 {
                    return Err(format!("header +{:#04x}: offset 0", 4 * i));
                }
                continue;
            }
            if p < 0xa0 || p >= g.len() {
                return Err(format!("header +{:#04x}: offset {p:#x} outside {:#x}..{:#x}", 4 * i, 0xa0, g.len()));
            }
            if let Some(o) = out.iter().find(|o| o.1 == p) {
                return Err(format!("header +{:#04x} and +{:#04x}: the same offset {p:#x}", o.0, 4 * i));
            }
            out.push((4 * i, p));
        }
        f.fill(0x9c, 4, 0, "header +0x9c")?;
        Ok(out)
    })();
    if let Err(e) = &r {
        h.fail(e.clone());
    }
    r
}

fn bad(what: &str, at: usize, v: usize, want: &str) -> String {
    format!("{what} at +{at:#x}: {v:#x}, expected {want}")
}

/// Alignment padding after a table's last field: fewer than `lim` bytes, all zero.
fn pad_to(f: &mut Fields, end: usize, lim: usize) -> Result<(), String> {
    let span = f.b.len();
    if end > span || span - end >= lim {
        return Err(format!("table ends at +{end:#x}, its extent is {span:#x} bytes (expected under {lim} bytes of padding)"));
    }
    f.fill(end, span - end, 0, "alignment padding")
}

fn pad(f: &mut Fields, end: usize) -> Result<(), String> {
    pad_to(f, end, 16)
}

/// A table whose size is its header plus `n * stride` bytes: returns n.
fn counted(f: &mut Fields, stride: usize) -> Result<usize, String> {
    let n = f.u32(0)? as usize;
    f.fill(4, 12, 0, "header words +4 to +0xC")?;
    let end = n.checked_mul(stride).and_then(|b| b.checked_add(0x10)).ok_or_else(|| bad("record count", 0, n, "a count that fits"))?;
    if end > f.b.len() {
        return Err(bad("record count", 0, n, &format!("{} records of {stride:#x} bytes within {:#x}", n, f.b.len())));
    }
    Ok(n)
}

fn plain_records(f: &mut Fields, stride: usize) -> Result<(), String> {
    // The loader copies the records whole; no reader of their fields is established, so their bytes stay unread.
    let n = counted(f, stride)?;
    pad(f, 0x10 + n * stride)
}

fn records_80(f: &mut Fields, _c: &Ctx) -> Result<(), String> {
    plain_records(f, 0x80)
}

/// +0x04: the light sets. The loader copies at most 12 records; func_L01_00438968 reads the vector at +0x10 of each,
/// func_003DB5C0 (func_L01_004A3D80) the other rows, and the terrain light pass func_L01_004AEC50 all four rows (LQC2 at +0,
/// +0x10, +0x20, +0x30).
fn light_sets(f: &mut Fields, _c: &Ctx, out: &mut Out) -> Result<(), String> {
    let n = u32_at(f.b, 0)? as usize;
    if n > 12 {
        return Err(bad("record count", 0, n, "at most 12 (the loader copies no more)"));
    }
    let n = counted(f, 0x40)?;
    for i in 0..n {
        let r = 0x10 + 0x40 * i;
        let row = |o: usize| -> Result<[f32; 4], String> {
            let mut v = [0f32; 4];
            for (k, x) in v.iter_mut().enumerate() {
                *x = f32::from_bits(u32_at(f.b, r + o + 4 * k)?);
            }
            Ok(v)
        };
        let rows = [row(0)?, row(0x10)?, row(0x20)?, row(0x30)?];
        if let Some(v) = rows.iter().flatten().find(|v| !v.is_finite()) {
            return Err(format!("light set {i}: {v}"));
        }
        out.light_sets.push(LightSet { colour: [rows[0], rows[2]], direction: [rows[1], rows[3]] });
        f.mark(r, 0x40);
    }
    pad(f, 0x10 + 0x40 * n)
}

/// +0x08: the loads of the camera code and the camera init.
fn cameras(f: &mut Fields, _c: &Ctx) -> Result<(), String> {
    let n = counted(f, 0x20)?;
    for i in 0..n {
        let r = 0x10 + 0x20 * i;
        // u32 +0, floats +4 to +0xC and the class u16 at +0xC; floats +0x18, +0x1C (entry index); +0xE and +0x10 to +0x17 are read by nothing.
        f.mark(r, 0xe);
        f.mark(r + 0x18, 8);
        f.skip(r + 0xe, 2);
        f.skip(r + 0x10, 8);
    }
    pad(f, 0x10 + 0x20 * n)
}

/// The +0x0C records by type (the s16 at +0): the record bytes the type's handler loads, the entry's size, the entry bytes it loads
/// (the handler is the one func_L01_004A7680 takes from the table at 0x2F7800: a data-flow over the handler and the functions of its
/// code region that follows the record pointer in a0, and the entry pointer the handler loads from the record's +8, through the
/// calls, the stores of a pointer to constant addresses and their loads: captures/agent-gp4/rec.py over the 34 overlays).
const REC90: &[(i16, &[(u16, u16)], usize, &[(u16, u16)])] = &[
    (0, &[(12, 4), (64, 16)], 32, &[(0, 24)]),
    (1, &[(16, 112)], 32, &[(0, 28)]),
    (3, &[(64, 64)], 16, &[(0, 8)]),
    (6, &[(64, 64)], 32, &[(0, 20)]),
    (9, &[(64, 64)], 32, &[(0, 20)]),
    (10, &[(16, 112)], 48, &[(0, 48)]),
];

/// The type's row of `REC90`.
fn rec90_type(b: &[u8], at: usize) -> Result<&'static (i16, &'static [(u16, u16)], usize, &'static [(u16, u16)]), String> {
    let t = i16::from_le_bytes([b[at], b[at + 1]]);
    REC90.iter().find(|r| r.0 == t).ok_or_else(|| bad("record type", at, t as usize, "one of 0, 1, 3, 6, 9, 10"))
}

/// +0x0C: the type, the two words the type's handler setup writes, the entry index and the fields the type's handler loads; the
/// rest of the record (and the 16 bytes at +0x80, which no handler loads) is skipped.
fn records_90(f: &mut Fields, _c: &Ctx) -> Result<(), String> {
    let n = counted(f, 0x90)?;
    for i in 0..n {
        let r = 0x10 + 0x90 * i;
        let row = rec90_type(f.b, r)?;
        f.mark(r, 2);
        f.fill(r + 2, 2, 0, "record +2 (written by func_L01_004A7680)")?;
        f.fill(r + 4, 4, 0, "record +4 (written by func_L01_004A7680)")?;
        f.u32(r + 8)?;
        let mut read = [false; 0x90];
        for k in &mut read[..12] {
            *k = true;
        }
        for &(o, l) in row.1 {
            f.mark(r + o as usize, l as usize);
            for k in &mut read[o as usize..(o + l) as usize] {
                *k = true;
            }
        }
        skip_unread(f, r, &read);
    }
    pad(f, 0x10 + 0x90 * n)
}

/// Skips the runs of `read` that are false, `base` bytes into the fields.
fn skip_unread(f: &mut Fields, base: usize, read: &[bool]) {
    let mut x = 0;
    while x < read.len() {
        if read[x] {
            x += 1;
            continue;
        }
        let s = x;
        while x < read.len() && !read[x] {
            x += 1;
        }
        f.skip(base + s, x - s);
    }
}

/// +0x68: the loads of the level code (every byte of a row is loaded by some function: the centre, the matrix rows, the angles
/// row and the rows before the centre).
fn volumes_cuboid(f: &mut Fields, _c: &Ctx) -> Result<(), String> {
    let n = counted(f, 0x80)?;
    f.mark(0x10, 0x80 * n);
    pad(f, 0x10 + 0x80 * n)
}

/// +0x6C: the first row, the centre and the three matrix rows; the rows at +0x10, +0x20 and +0x70 are read by nothing.
fn volumes_sphere(f: &mut Fields, _c: &Ctx) -> Result<(), String> {
    let n = counted(f, 0x80)?;
    for i in 0..n {
        let r = 0x10 + 0x80 * i;
        f.mark(r, 0x10);
        f.mark(r + 0x30, 0x40);
        f.skip(r + 0x10, 0x20);
        f.skip(r + 0x70, 0x10);
    }
    pad(f, 0x10 + 0x80 * n)
}

