const G: &str = "LEVEL gameplay (unpacked)";

/// What the gameplay block gives the port.
pub struct Gameplay {
    /// The +0x04 table: the level's light sets, which func_L01_004252F0 copies to 0x1F17C0 and the terrain light pass
    /// (func_L01_004AEC50) indexes by the nibbles of each light table entry's +6.
    pub light_sets: Vec<LightSet>,
    /// The +0x00 table's fog.
    pub fog: Fog,
    /// The +0x90 table's first group, one pair per core terrain chunk: (key, id). None in the levels without the table.
    pub chunk_zones: Option<Vec<ChunkZone>>,
    /// The settings table's +0x68: the level chunk records (func_L01_004252F0 stores it at 0x1F3FCC).
    pub level_chunks: usize,
    /// The +0x34 table: the tie instances, in the order of the game's tie instance array ([0x1E0F54], 32 bytes each).
    pub ties: Vec<TieInstance>,
    /// The +0x40 table: the shrub instances.
    pub shrubs: Vec<ShrubInstance>,
    /// The +0x90 table's second group, one pair per tie instance: (key, id). None in the levels without the table.
    pub tie_zones: Option<Vec<TieZone>>,
}

/// A tie instance (0x60 bytes), as func_L01_004252F0 (0x425A40 to 0x425CF0) builds the instance array (32 bytes each, [0x1E0F54])
/// and the matrix array (64 bytes each, [0x1E0F5C]) from it.
pub struct TieInstance {
    /// +0: the tie class id (a class record's +4), mapped by the byte table at 0x23C880 to the class slot at instance +0x1D.
    pub class: u32,
    /// +4: the loader keeps min(+4 >> 4, 255) at instance +0x1C.
    pub distance: u32,
    /// +0xC: the instance id, the loader's instance +0x10 (the visibility pairs name it).
    pub id: u32,
    /// +0x10, +0x20, +0x30: the axes (rows 0 to 2 of the matrix array; the loader replaces each w by 1 over the row's length, and
    /// sets instance +0x1E flag 8 when their determinant is negative).
    pub axes: [[f32; 3]; 3],
    /// +0x40: the position (row 3; the loader replaces its w by the class's +0x40 scale).
    pub position: [f32; 3],
}

/// A shrub instance (0x70 bytes), as func_L01_004252F0 builds the shrub array (0x20 bytes each, [0x1E0E48]) and the matrix array
/// (0x40 bytes each, [0x1E0E50]) from it.
pub struct ShrubInstance {
    /// +0: the shrub class id (a class record's +4), mapped by the byte table at 0x238670.
    pub class: u32,
    /// +4: the draw distance (at least 16.0).
    pub draw_distance: f32,
    /// +0x10, +0x20, +0x30: the axes (rows 0 to 2; the loader replaces each w).
    pub axes: [[f32; 3]; 3],
    /// +0x40: the position (row 3).
    pub position: [f32; 3],
    /// +0x50, +0x54, +0x58: the colour bytes the loader packs with 0x80.
    pub colour: [u8; 3],
}

/// A tie instance's visibility pair (+0x90 table, second group): the loader gives the tie whose id (instance +0x10) is `id` the u16
/// (key >> 3) << 8 | 1 << (key & 7) at its +0x10 (`Gameplay::tie_keys`).
#[derive(Clone, Copy)]
pub struct TieZone {
    pub key: u32,
    pub id: u32,
}

impl Gameplay {
    /// Each tie instance's visibility mask and zone byte (instance +0x10, +0x11 after the load), as func_L01_004252F0 gives them
    /// (0x4279E0 to 0x427D58): with no visibility grid (`has_grid`, the core index's word 3) or no +0x90 table, 0x7F80 (mask
    /// 0x80, zone 0x7F) for every tie; when the pairs are as many as the ties and pair i's id is tie i's id, tie i gets pair i's
    /// key; otherwise each tie gets the key of the last pair with its id (a table of 0x4000 entries filled in pair order with
    /// the key's low 16 bits), and 0x7F80 when no pair has it, its id is 0x4000 or more, or that key is negative as an s16.
    pub fn tie_keys(&self, has_grid: bool) -> Vec<(u8, u8)> {
        let cleared = (0x80u8, 0x7fu8);
        let enc = |key: i32| (1u8 << (key & 7), ((key >> 3) & 0xff) as u8);
        let Some(pairs) = self.tie_zones.as_ref().filter(|_| has_grid) else { return vec![cleared; self.ties.len()] };
        if pairs.len() == self.ties.len() && pairs.iter().zip(&self.ties).all(|(p, t)| p.id == t.id & 0xffff) {
            return pairs.iter().map(|p| enc(p.key as i32)).collect();
        }
        let mut table = vec![-2i16; 0x4000];
        for p in pairs {
            if p.id < 0x4000 {
                table[p.id as usize] = p.key as u16 as i16;
            }
        }
        self.ties
            .iter()
            .map(|t| {
                let id = (t.id & 0xffff) as usize;
                match table.get(id) {
                    Some(&k) if k >= 0 => enc(k as i32),
                    _ => cleared,
                }
            })
            .collect()
    }
}

/// A terrain chunk's visibility key: func_L01_004252F0 gives a chunk the u16 (key >> 3) << 8 | 1 << (key & 7) at +0x3A, the mask
/// and zone byte func_L01_004ADC98 tests against the frame's zone record (`terrain::ZoneKeys` says which chunk gets which pair).
#[derive(Clone, Copy)]
pub struct ChunkZone {
    pub key: u32,
    pub id: u8,
}

/// The tables' data while the block is walked; `gameplay` checks that every table the port takes was there.
#[derive(Default)]
struct Out {
    light_sets: Vec<LightSet>,
    fog: Option<Fog>,
    chunk_zones: Option<Vec<ChunkZone>>,
    level_chunks: Option<usize>,
    ties: Option<Vec<TieInstance>>,
    shrubs: Option<Vec<ShrubInstance>>,
    tie_zones: Option<Vec<TieZone>>,
}

/// The level's distance fog (the settings table +0x0C to +0x24), as the world's VU1 programs and the GS apply it. Veldin, field
/// 2400: the GS's FOGCOL is 0x50737D (+0x0C, +0x10, +0x14), and the terrain program's per-frame constants are what these
/// give: F = clamp(w + 293.25, 140.25, 255) with w = -0.765 x the view depth (293.25 = 255 + 0.765 x 50, 0.765 = (255 - 140.25)
/// / (200 - 50)).
pub struct Fog {
    /// FOGCOL: red, green, blue.
    pub colour: [u8; 3],
    /// The view depths (world units; the table holds them x 1024) where the fog value is `near_f` and `far_f`.
    pub near: f32,
    pub far: f32,
    /// The GS fog value F at those depths (255: no fog), linear between them and held beyond: the pixel is (F x colour + (255 -
    /// F) x FOGCOL) / 256.
    pub near_f: f32,
    pub far_f: f32,
}

/// A light set (0x40 bytes): two directional lights, each a colour row then a direction row.
pub struct LightSet {
    /// +0x00 and +0x20: each light's colour (x, y, z: red, green, blue, 1.0 = 0x80 on the GS) and in w the factor a negative dot
    /// product is scaled by (func_L01_004AEC50 lights by max(d, d * w)).
    pub colour: [[f32; 4]; 2],
    /// +0x10 and +0x30: each light's direction (x, y, z), dotted with the vertex normal; w is added in when two sets are blended
    /// and read by nothing else.
    pub direction: [[f32; 4]; 2],
}

