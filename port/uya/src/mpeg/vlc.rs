/// What a macroblock_type code says (tables B.2 to B.4).
pub const QUANT: i16 = 1;
pub const FWD: i16 = 2;
pub const BWD: i16 = 4;
pub const PATTERN: i16 = 8;
pub const INTRA: i16 = 16;

/// Table B.2: macroblock_type in I pictures.
pub fn mb_type_i() -> &'static Vlc {
    static T: OnceLock<Vlc> = OnceLock::new();
    T.get_or_init(|| Vlc::build(&[("1", INTRA), ("01", QUANT | INTRA)]))
}

/// Table B.3: macroblock_type in P pictures.
pub fn mb_type_p() -> &'static Vlc {
    static T: OnceLock<Vlc> = OnceLock::new();
    T.get_or_init(|| {
        Vlc::build(&[
            ("1", FWD | PATTERN),
            ("01", PATTERN),
            ("001", FWD),
            ("00011", INTRA),
            ("00010", QUANT | FWD | PATTERN),
            ("00001", QUANT | PATTERN),
            ("000001", QUANT | INTRA),
        ])
    })
}

