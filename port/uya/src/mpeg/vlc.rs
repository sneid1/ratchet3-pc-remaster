//! The variable length code tables of ISO 13818-2 annex B (Main Profile, 4:2:0), written as the standard lists them (the code's bits
//! as text, with the sign bit left off where the standard's rows are pairs) and turned into lookup tables on first use.

use std::sync::OnceLock;

/// A table that reads up to `max` bits: the entry at the next `max` bits is (value, code length); a length of 0 is no code.
pub struct Vlc {
    max: u32,
    t: Vec<(i16, u8)>,
}

impl Vlc {
    fn build(codes: &[(&str, i16)]) -> Vlc {
        let max = codes.iter().map(|c| c.0.len()).max().expect("codes") as u32;
        let mut t = vec![(0i16, 0u8); 1 << max];
        for &(code, v) in codes {
            let n = code.len() as u32;
            let bits = u32::from_str_radix(code, 2).expect("a code of 0 and 1");
            let lo = (bits << (max - n)) as usize;
            for e in &mut t[lo..lo + (1 << (max - n))] {
                assert!(e.1 == 0, "VLC table: code {code} collides with another");
                *e = (v, n as u8);
            }
        }
        Vlc { max, t }
    }

    /// The next code's value and its length in bits, None where the bits are no code.
    #[inline]
    pub fn look(&self, bits: &super::bits::Bits) -> Option<(i16, u32)> {
        let (v, n) = self.t[bits.peek(self.max) as usize];
        (n != 0).then_some((v, n as u32))
    }
}

